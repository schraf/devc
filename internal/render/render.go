// Package render turns a definition into a Dockerfile and an in-memory build context.
package render

import (
	"archive/tar"
	"bytes"
	"fmt"
	"os"
	"path"
	"path/filepath"
	"slices"
	"sort"
	"strings"

	"github.com/schraf/devcontainer/internal/config"
	"github.com/schraf/devcontainer/internal/features"
)

// corePackages are needed by the generated Dockerfile and most feature snippets.
var corePackages = []string{"ca-certificates", "curl", "git", "gnupg", "tzdata",
	"less", "locales", "man-db", "openssh-client", "procps", "unzip", "wget", "zip"}

// Dockerfile renders the Dockerfile for cfg. cfg is validated first.
func Dockerfile(cfg *config.Config) (string, error) {
	if err := features.Validate(cfg); err != nil {
		return "", err
	}
	enabled := enabledFeatures(cfg)
	u := cfg.User
	home := "/home/" + u.Name
	var b strings.Builder
	line := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }
	stage := func(s features.Stage) error {
		for _, f := range enabled {
			out, err := f.Render(cfg, s)
			if err != nil {
				return fmt.Errorf("feature %s: %w", f.Name, err)
			}
			if out = strings.TrimSpace(out); out != "" {
				line("\n# --- %s ---\n%s", f.Name, out)
			}
		}
		return nil
	}

	line("# syntax=docker/dockerfile:1")
	line("# Generated by devc from %s (%s). Edit the YAML, not this file.", cfg.Name, filepath.Base(cfg.Path))
	line("FROM %s", cfg.Base)
	line("")
	env := [][2]string{{"DEBIAN_FRONTEND", "noninteractive"}, {"LANG", "C.UTF-8"}, {"LC_ALL", "C.UTF-8"}}
	if cfg.Timezone != "" {
		env = append(env, [2]string{"TZ", cfg.Timezone})
	}
	if len(cfg.Certs) > 0 {
		for _, k := range []string{"SSL_CERT_FILE", "REQUESTS_CA_BUNDLE", "NODE_EXTRA_CA_CERTS"} {
			env = append(env, [2]string{k, "/etc/ssl/certs/ca-certificates.crt"})
		}
	}
	for _, k := range sortedKeys(cfg.Env) {
		env = append(env, [2]string{k, cfg.Env[k]})
	}
	writeEnv(&b, env)

	if len(cfg.Certs) > 0 {
		line("\n# Extra trusted root CAs, added to the system trust store by update-ca-certificates")
		line("COPY certs/ /usr/local/share/ca-certificates/extra/")
	}

	pkgs := append([]string{}, corePackages...)
	if u.Sudo {
		pkgs = append(pkgs, "sudo")
	}
	for _, f := range enabled {
		pkgs = append(pkgs, f.Apt...)
	}
	pkgs = dedupe(pkgs)
	line("\nRUN apt-get update && apt-get install -y --no-install-recommends \\")
	for i := 0; i < len(pkgs); i += 8 {
		line("        %s \\", strings.Join(pkgs[i:min(i+8, len(pkgs))], " "))
	}
	line("    && update-ca-certificates \\")
	line("    && rm -rf /var/lib/apt/lists/*")

	if err := stage(features.StageSystem); err != nil {
		return "", err
	}

	line("\n# Non-root user (Ubuntu ships \"ubuntu\" at UID 1000; remove it)")
	line("RUN (userdel -r ubuntu 2>/dev/null || true) \\")
	line("    && groupadd --gid %d %s \\", u.GID, u.Name)
	line("    && useradd --uid %d --gid %d -m -s %s %s \\", u.UID, u.GID, u.Shell, u.Name)
	for _, g := range groups(enabled) {
		line("    && usermod -aG %s %s \\", g, u.Name)
	}
	if u.Sudo {
		line("    && echo \"%s ALL=(ALL) NOPASSWD:ALL\" > /etc/sudoers.d/%s \\", u.Name, u.Name)
		line("    && chmod 0440 /etc/sudoers.d/%s \\", u.Name)
	}
	line("    && true")

	dirs := userDirs(cfg, enabled, home)
	line("\n# Directories owned by the user. Persisted ones are usually mounted as volumes; creating")
	line("# them here means Docker seeds each empty volume with the right ownership.")
	line("RUN install -d -o %d -g %d \\", u.UID, u.GID)
	for i, d := range dirs {
		if i == len(dirs)-1 {
			line("        %s", d)
		} else {
			line("        %s \\", d)
		}
	}
	if slices.Contains(dirs, home+"/.ssh") {
		line("RUN chmod 700 %s/.ssh", home)
	}

	line("\nUSER %s", u.Name)
	line("ENV HOME=%s", home)
	if err := writeFiles(&b, cfg, home); err != nil {
		return "", err
	}
	if err := stage(features.StageUser); err != nil {
		return "", err
	}
	line("\nUSER root")
	if err := stage(features.StageLate); err != nil {
		return "", err
	}

	if extra := strings.TrimSpace(cfg.ExtraDockerfile); extra != "" {
		line("\n# --- extra_dockerfile ---\n%s", extra)
	}

	line("\nWORKDIR %s", cfg.Workdir)
	if entrypoint(enabled) {
		line("COPY entrypoint.sh /usr/local/bin/entrypoint.sh")
		line("RUN chmod +x /usr/local/bin/entrypoint.sh")
		line("# Runs as %s and uses sudo to start dockerd, so `docker exec` defaults to %s too.", u.Name, u.Name)
		line(`ENTRYPOINT ["/usr/local/bin/entrypoint.sh"]`)
	}
	line("USER %s", u.Name)
	line(`CMD ["sleep", "infinity"]`)
	return b.String(), nil
}

// Context renders the Dockerfile and packs it with every file it references into a tar
// archive, ready to stream to `docker build -`.
func Context(cfg *config.Config) ([]byte, error) {
	df, err := Dockerfile(cfg)
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	tw := tar.NewWriter(&buf)
	add := func(name string, mode int64, data []byte) error {
		if err := tw.WriteHeader(&tar.Header{Name: name, Mode: mode, Size: int64(len(data)), Typeflag: tar.TypeReg}); err != nil {
			return err
		}
		_, err := tw.Write(data)
		return err
	}
	if err := add("Dockerfile", 0o644, []byte(df)); err != nil {
		return nil, err
	}
	for _, c := range cfg.Certs {
		data, err := os.ReadFile(cfg.ResolvePath(c))
		if err != nil {
			return nil, err
		}
		if err := add(path.Join("certs", filepath.Base(c)), 0o644, data); err != nil {
			return nil, err
		}
	}
	if entrypoint(enabledFeatures(cfg)) {
		if err := add("entrypoint.sh", 0o755, features.Asset("entrypoint.sh")); err != nil {
			return nil, err
		}
	}
	if err := tw.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// heredoc is the delimiter for files written with COPY <<'…'.
const heredoc = "DEVC_EOF"

// writeFiles writes the definition's files into the user's home, owned by the user, before
// the user-stage features run (so e.g. TPM can read ~/.tmux.conf).
func writeFiles(b *strings.Builder, cfg *config.Config, home string) error {
	if len(cfg.Files) == 0 {
		return nil
	}
	paths := sortedKeys(cfg.Files)
	// Create parent directories as the user so none of them end up owned by root.
	var dirs []string
	for _, p := range paths {
		if d := path.Dir(p); d != "." {
			dirs = append(dirs, path.Join(home, d))
		}
	}
	fmt.Fprintf(b, "\n# --- files ---\n")
	if dirs = dedupe(dirs); len(dirs) > 0 {
		fmt.Fprintf(b, "RUN mkdir -p %s\n", strings.Join(dirs, " "))
	}
	for _, p := range paths {
		content := cfg.Files[p]
		if strings.Contains("\n"+content+"\n", "\n"+heredoc+"\n") {
			return fmt.Errorf("files %s: content contains the line %s", p, heredoc)
		}
		if content != "" && !strings.HasSuffix(content, "\n") {
			content += "\n"
		}
		fmt.Fprintf(b, "COPY --chown=%d:%d <<'%s' %s\n%s%s\n", cfg.User.UID, cfg.User.GID, heredoc, path.Join(home, p), content, heredoc)
	}
	return nil
}

func enabledFeatures(cfg *config.Config) []*features.Feature {
	var out []*features.Feature
	for _, f := range features.All() {
		if cfg.Enabled(f.Name) {
			out = append(out, f)
		}
	}
	return out
}

func entrypoint(enabled []*features.Feature) bool {
	for _, f := range enabled {
		if f.Entrypoint {
			return true
		}
	}
	return false
}

func groups(enabled []*features.Feature) []string {
	var out []string
	for _, f := range enabled {
		out = append(out, f.Groups...)
	}
	return dedupe(out)
}

// userDirs lists the user-owned directories to create, including every parent below $HOME so
// none of them end up owned by root.
func userDirs(cfg *config.Config, enabled []*features.Feature, home string) []string {
	var rel []string
	rel = append(rel, cfg.Persist...)
	for _, f := range enabled {
		rel = append(rel, f.Dirs...)
	}
	var out []string
	for _, d := range rel {
		if path.IsAbs(d) {
			out = append(out, d)
			continue
		}
		parts := strings.Split(path.Clean(d), "/")
		for i := range parts {
			out = append(out, path.Join(home, path.Join(parts[:i+1]...)))
		}
	}
	out = append(out, cfg.Workdir)
	out = dedupe(out)
	sort.Strings(out)
	return out
}

func writeEnv(b *strings.Builder, env [][2]string) {
	for i, kv := range env {
		prefix, suffix := "    ", " \\"
		if i == 0 {
			prefix = "ENV "
		}
		if i == len(env)-1 {
			suffix = ""
		}
		fmt.Fprintf(b, "%s%s=%s%s\n", prefix, kv[0], quoteEnv(kv[1]), suffix)
	}
}

// quoteEnv double-quotes a Dockerfile ENV value when it needs it.
func quoteEnv(v string) string {
	if v != "" && !strings.ContainsAny(v, " \t\"'\\$#") {
		return v
	}
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`, `$`, `\$`).Replace(v) + `"`
}

func dedupe(in []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, s := range in {
		if s != "" && !seen[s] {
			seen[s] = true
			out = append(out, s)
		}
	}
	return out
}

func sortedKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
